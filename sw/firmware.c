void main() {
    print_val(0x11111111); // BASLA

    int32_t output_image[WIDTH*HEIGHT];

    // KENAR TESPITI (SOBEL FILTER)
    // Donanim mantigini burada basitlestirerek kullaniyoruz.
    // Her pikselin altindaki ve ustundeki deger farkina bakiyoruz.
    
    for(int y=1; y < HEIGHT-1; y++) {
        for(int x=1; x < WIDTH-1; x++) {
            
            // Pikselin kendisi
            // int32_t p_center = image_data[y*WIDTH + x];
            
            // Ustundeki ve altindaki pikseller
            int32_t p_top = image_data[(y-1)*WIDTH + x];
            int32_t p_bot = image_data[(y+1)*WIDTH + x];
            
            // Basit Kenar Tespiti: (Alt - Ust) farki yuksekse orada bir cizgi vardir.
            int32_t diff = (p_bot - p_top) * 4; // Kontrasti artir
            
            if(diff < 0) diff = -diff; // Mutlak deger al
            output_image[y*WIDTH+x] = diff;
        }
    }

    print_val(0xAAAAAAAA); // ISLEM BITTI, CIZIME GEC

    // --- ASCII CIZIM MODU ---
    for(int y=0; y<HEIGHT; y++) {
        for(int x=0; x<WIDTH; x++) {
            int32_t val = output_image[y*WIDTH+x];
            
            // Eger fark (val) buyukse, orada bir kenar vardir -> @
            // Eger fark kucukse, duz alandir -> .
            if (val > 50) { 
                print_char('@'); 
                print_char('@'); // Daha dolgun gorunsun
            } else {
                print_char('.'); 
                print_char(' '); 
            }
        }
        print_char('\n'); // Satir atla
    }

    print_val(0xFFFFFFFF); // SON
}